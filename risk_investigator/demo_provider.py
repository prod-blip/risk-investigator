"""Explicitly scripted, no-network provider for demonstrating the orchestration loop."""

import json

from .provider import ProviderReply


class DemoProvider:
    kind = "demo"
    model = "scripted-demo-not-an-llm"

    def prepare(self, input_items, instructions, tools, report_schema, max_output_tokens):
        return {"input": input_items, "instructions": instructions, "tools": tools}

    def respond(self, payload: dict, *, timeout: float) -> ProviderReply:
        records, errors = {}, []
        for item in payload["input"]:
            if item.get("type") == "function_call_output":
                result = json.loads(item["output"])
                if "error" in result:
                    errors.append(result)
                else:
                    records[result["tool"]] = result
        if errors:
            return self._final(records, None, "inconclusive", "A demonstration tool failed; evidence is insufficient.")
        if "incident_context" not in records:
            return self._call("incident_context", {}, records)
        if not records["incident_context"]["data"]["analysis_window_complete"]:
            return self._final(records, None, "inconclusive", "The configured analysis window is incomplete.")
        sequence = (("compare_cohorts", {"group_by": "channel"}), ("feature_health", {}),
                    ("deployment_history", {}), ("linked_activity", {"min_accounts": 5}),
                    ("outcome_metrics", {}))
        for name, args in sequence:
            if name not in records:
                return self._call(name, args, records)
        health = records["feature_health"]["data"]["periods"]
        policies = records["deployment_history"]["data"]["policies"]
        linkage = records["linked_activity"]["data"]["periods"]
        candidates = []
        if (health["after"]["missing"] > health["before"]["missing"]
                and health["after"]["source_delivery_mismatches"] > health["before"]["source_delivery_mismatches"]):
            candidates.append("broken_signal")
        if (len(policies["before"]) == len(policies["after"]) == 1
                and policies["after"][0]["decline_threshold"] < policies["before"][0]["decline_threshold"]):
            candidates.append("restrictive_rule")
        if linkage["after"]["young_new_device_low_velocity"] > linkage["before"]["young_new_device_low_velocity"]:
            candidates.append("emerging_fraud")
        if len(candidates) != 1:
            return self._final(records, None, "inconclusive",
                               "The scripted demonstration cannot establish one cause from the available evidence.")
        cause = candidates[0]
        response = {"broken_signal": "restore_device_signal", "restrictive_rule": "previous_threshold",
                    "emerging_fraud": "linked_activity_control"}[cause]
        if "replay" not in records:
            return self._call("replay", {"response": response, "min_accounts": 5}, records)
        status, diagnosis = "supported", cause
        if cause == "emerging_fraud":
            outcomes = records["outcome_metrics"]["data"]
            periods = outcomes["periods"]
            mature = min(periods["before"]["label_coverage"], periods["after"]["label_coverage"]) >= 0.9
            if not mature or not outcomes["confirmed_fraud_in_linked_after_groups"]:
                status, diagnosis = "suspected", "suspected_emerging_fraud"
        return self._final(records, diagnosis, status,
                           "Evidence and a sandbox response test are ready for human review. "
                           "This conclusion was generated by a scripted demonstration, not an LLM.")

    def _call(self, name: str, arguments: dict, records: dict) -> ProviderReply:
        index = len(records) + 1
        return ProviderReply([{"type": "function_call", "id": f"fc_demo_{index}",
                               "call_id": f"call_demo_{index}", "name": name,
                               "arguments": json.dumps(arguments)}])

    def _final(self, records: dict, diagnosis: str | None, status: str, summary: str) -> ProviderReply:
        observations = {
            "incident_context": ("The analysis window completeness is recorded.", "/data/analysis_window_complete"),
            "compare_cohorts": ("The after-period decline rate is recorded.", "/data/totals/after/decline_rate_pct"),
            "feature_health": ("The delivered device signal has the recorded missing count.", "/data/periods/after/missing"),
            "deployment_history": ("The effective after-period policies are recorded.", "/data/policies/after"),
            "linked_activity": ("The observed linked-account pattern has this transaction count.",
                                "/data/periods/after/young_new_device_low_velocity"),
            "outcome_metrics": ("The after-period outcome coverage is recorded.", "/data/periods/after/label_coverage"),
            "replay": ("The sandbox response changes the recorded number of decisions.", "/data/changed_decisions"),
        }
        findings = [{"interpretation": observations[name][0], "evidence_id": record["evidence_id"],
                     "json_pointer": observations[name][1]} for name, record in records.items()]
        hypotheses = []
        for cause, tool in (("broken_signal", "feature_health"), ("restrictive_rule", "deployment_history"),
                            ("emerging_fraud", "linked_activity")):
            record = records.get(tool, records.get("incident_context"))
            if record is not None:
                hypotheses.append({"category": cause, "description": cause,
                                   "verdict": "supported" if diagnosis == cause and status == "supported" else "unresolved",
                                   "evidence_ids": [record["evidence_id"]]})
        proposal = {
            "status": status, "diagnosis": diagnosis, "summary": summary,
            "findings": findings, "hypotheses": hypotheses,
            "response_evidence_id": records["replay"]["evidence_id"] if "replay" in records else None,
            "limitations": ["Scripted demo only: no foundation model was called.",
                            "Synthetic replay assumptions and time-eligible outcome coverage limit the conclusions."],
        }
        return ProviderReply([{"type": "message", "role": "assistant", "content": [
            {"type": "output_text", "text": json.dumps(proposal)}]}])
